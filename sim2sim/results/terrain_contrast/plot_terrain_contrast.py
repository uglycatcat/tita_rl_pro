#!/usr/bin/env python3
"""Plot key terrain generalization metrics from terrain_contrast results."""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


KEY_METRICS = [
    ("vx_mae_mujoco", "VX MAE", "lower"),
    ("yaw_mae_mujoco", "Yaw MAE", "lower"),
    ("roll_rms_mujoco", "Roll RMS", "lower"),
    ("pitch_rms_mujoco", "Pitch RMS", "lower"),
    ("survival_time_s_mujoco", "Survival Time (s)", "higher"),
    ("fall_rate_mujoco", "Fall Rate", "lower"),
    ("action_delta_rate_mean_mujoco", "Action Delta Rate", "lower"),
]


def parse_args():
    parser = argparse.ArgumentParser(description="Plot terrain contrast key figures.")
    parser.add_argument(
        "--input-csv",
        default="sim2sim/results/terrain_contrast/compare.csv",
        help="Path to compare.csv generated by experiment suite.",
    )
    parser.add_argument(
        "--output-dir",
        default="sim2sim/results/terrain_contrast/figure",
        help="Directory to save generated figures.",
    )
    parser.add_argument(
        "--timeseries-dir",
        default="sim2sim/results/terrain_contrast/mujoco",
        help="Directory containing per-run mujoco csv files.",
    )
    parser.add_argument(
        "--repeat-id",
        type=int,
        default=0,
        help="Use this repeat_id for terrain timeseries plots (default: 0).",
    )
    return parser.parse_args()


def load_and_aggregate(input_csv: Path) -> pd.DataFrame:
    df = pd.read_csv(input_csv)
    df["terrain"] = df["scenario_id"].str.split("_", n=1).str[0]

    metric_cols = [m for m, _, _ in KEY_METRICS]
    grouped = df.groupby("terrain", sort=True)[metric_cols].agg(["mean", "std"])
    grouped = grouped.fillna(0.0)
    return grouped


def load_raw_compare(input_csv: Path) -> pd.DataFrame:
    df = pd.read_csv(input_csv)
    df["terrain"] = df["scenario_id"].str.split("_", n=1).str[0]
    return df


def save_summary_csv(summary: pd.DataFrame, output_dir: Path):
    flat_columns = []
    for metric, _, _ in KEY_METRICS:
        flat_columns.extend([f"{metric}_mean", f"{metric}_std"])
    summary_flat = summary.copy()
    summary_flat.columns = flat_columns
    summary_flat.to_csv(output_dir / "terrain_key_metrics_summary.csv", index=True)


def plot_key_metrics(summary: pd.DataFrame, output_dir: Path):
    terrains = summary.index.to_list()
    fig, axes = plt.subplots(2, 3, figsize=(14, 8))
    fig.suptitle("Terrain Generalization: Core Metrics", fontsize=14)

    core = KEY_METRICS[:6]
    x = np.arange(len(terrains))
    for idx, (metric, title, _) in enumerate(core):
        ax = axes[idx // 3, idx % 3]
        y = summary[(metric, "mean")].to_numpy()
        yerr = summary[(metric, "std")].to_numpy()
        ax.bar(x, y, yerr=yerr, capsize=4)
        ax.set_title(title)
        ax.set_xticks(x, terrains)
        ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()
    fig.savefig(output_dir / "terrain_core_metrics.png", dpi=180)
    plt.close(fig)


def plot_control_metric(summary: pd.DataFrame, output_dir: Path):
    terrains = summary.index.to_list()
    metric, title, _ = KEY_METRICS[6]
    x = np.arange(len(terrains))

    fig, ax = plt.subplots(figsize=(7, 4.5))
    y = summary[(metric, "mean")].to_numpy()
    yerr = summary[(metric, "std")].to_numpy()
    ax.bar(x, y, yerr=yerr, capsize=4, color="#4C78A8")
    ax.set_title(title)
    ax.set_xticks(x, terrains)
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()
    fig.savefig(output_dir / "terrain_action_delta_rate.png", dpi=180)
    plt.close(fig)


def plot_normalized_heatmap(summary: pd.DataFrame, output_dir: Path):
    terrains = summary.index.to_list()
    data = np.column_stack([summary[(metric, "mean")].to_numpy() for metric, _, _ in KEY_METRICS])
    normalized = np.zeros_like(data, dtype=float)

    for j, (_, _, direction) in enumerate(KEY_METRICS):
        col = data[:, j]
        col_min = np.nanmin(col)
        col_max = np.nanmax(col)
        if np.isclose(col_max, col_min):
            normalized[:, j] = 1.0
        elif direction == "lower":
            normalized[:, j] = (col_max - col) / (col_max - col_min)
        else:
            normalized[:, j] = (col - col_min) / (col_max - col_min)

    fig, ax = plt.subplots(figsize=(10, 4))
    im = ax.imshow(normalized, cmap="YlGn", aspect="auto", vmin=0.0, vmax=1.0)
    ax.set_title("Terrain Score Heatmap (0-1, higher is better)")
    ax.set_xticks(np.arange(len(KEY_METRICS)))
    ax.set_xticklabels([name for _, name, _ in KEY_METRICS], rotation=30, ha="right")
    ax.set_yticks(np.arange(len(terrains)))
    ax.set_yticklabels(terrains)

    for i in range(normalized.shape[0]):
        for j in range(normalized.shape[1]):
            ax.text(j, i, f"{normalized[i, j]:.2f}", ha="center", va="center", fontsize=8)

    cbar = fig.colorbar(im, ax=ax, shrink=0.9)
    cbar.set_label("Normalized score")
    fig.tight_layout()
    fig.savefig(output_dir / "terrain_score_heatmap.png", dpi=180)
    plt.close(fig)


def plot_generalization_retention(summary: pd.DataFrame, output_dir: Path):
    if "flat" not in summary.index:
        return

    flat = summary.loc["flat"]
    terrains = [t for t in summary.index.to_list() if t != "flat"]
    if not terrains:
        return

    specs = [
        ("vx_mae_mujoco", "VX Track", "lower"),
        ("yaw_mae_mujoco", "Yaw Track", "lower"),
        ("roll_rms_mujoco", "Roll", "lower"),
        ("pitch_rms_mujoco", "Pitch", "lower"),
        ("survival_time_s_mujoco", "Survival", "higher"),
        ("action_delta_rate_mean_mujoco", "Smoothness", "lower"),
    ]
    labels = [name for _, name, _ in specs]

    values = []
    for terrain in terrains:
        row = summary.loc[terrain]
        ratios = []
        for metric, _, direction in specs:
            base = float(flat[(metric, "mean")])
            val = float(row[(metric, "mean")])
            if np.isclose(base, 0.0) and np.isclose(val, 0.0):
                ratio = 1.0
            elif direction == "lower":
                ratio = base / max(val, 1e-12)
            else:
                ratio = val / max(base, 1e-12)
            ratios.append(ratio)
        values.append(ratios)

    x = np.arange(len(labels))
    width = 0.36
    colors = {"slope": "#F58518", "stairs": "#54A24B"}
    fig, ax = plt.subplots(figsize=(11, 4.8))
    for idx, terrain in enumerate(terrains):
        arr = np.array(values[idx], dtype=float)
        ax.bar(
            x + (idx - 0.5) * width,
            arr,
            width=width,
            label=terrain,
            color=colors.get(terrain, None),
            alpha=0.9,
        )

    ax.axhline(1.0, color="black", linestyle="--", linewidth=1.0, alpha=0.8)
    ax.set_title("Generalization Retention Relative to Flat (higher is better)")
    ax.set_ylabel("Retention ratio")
    ax.set_xticks(x, labels)
    ax.set_ylim(bottom=0.0)
    ax.grid(axis="y", alpha=0.3)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(output_dir / "terrain_generalization_retention.png", dpi=180)
    plt.close(fig)


def plot_repeat_variability(raw_df: pd.DataFrame, output_dir: Path):
    terrains = sorted(raw_df["terrain"].dropna().unique().tolist())
    if not terrains:
        return

    specs = [
        ("vx_mae_mujoco", "VX MAE"),
        ("survival_time_s_mujoco", "Survival Time (s)"),
        ("action_delta_rate_mean_mujoco", "Action Delta Rate"),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(14, 4.4))
    color_map = {"flat": "#4C78A8", "slope": "#F58518", "stairs": "#54A24B"}

    for ax, (metric, title) in zip(axes, specs):
        data = []
        for terrain in terrains:
            vals = pd.to_numeric(
                raw_df.loc[raw_df["terrain"] == terrain, metric],
                errors="coerce",
            ).dropna()
            data.append(vals.to_numpy())

        bp = ax.boxplot(data, patch_artist=True, labels=terrains, showfliers=False)
        for patch, terrain in zip(bp["boxes"], terrains):
            patch.set_facecolor(color_map.get(terrain, "#A0A0A0"))
            patch.set_alpha(0.45)

        rng = np.random.default_rng(0)
        for i, terrain in enumerate(terrains):
            vals = data[i]
            xj = rng.normal(i + 1, 0.035, size=len(vals))
            ax.scatter(
                xj,
                vals,
                s=28,
                color=color_map.get(terrain, "#707070"),
                alpha=0.9,
                edgecolor="white",
                linewidth=0.5,
                zorder=3,
            )

        ax.set_title(title)
        ax.grid(axis="y", alpha=0.25)

    fig.suptitle("Repeat-wise Distribution Across Terrains", fontsize=13)
    fig.tight_layout()
    fig.savefig(output_dir / "terrain_repeat_variability.png", dpi=180)
    plt.close(fig)


def plot_vx_error_cdf(timeseries_dir: Path, output_dir: Path):
    terrain_errors = {}
    for csv_path in sorted(timeseries_dir.glob("*_r*.csv")):
        scenario_id = csv_path.stem.rsplit("_r", 1)[0]
        terrain = scenario_id.split("_", 1)[0]
        df = pd.read_csv(csv_path)
        if not {"cmd_vx", "base_lin_vx"}.issubset(df.columns):
            continue
        err = np.abs(df["base_lin_vx"].to_numpy() - df["cmd_vx"].to_numpy())
        terrain_errors.setdefault(terrain, []).append(err)

    if not terrain_errors:
        return

    color_map = {"flat": "#4C78A8", "slope": "#F58518", "stairs": "#54A24B"}
    fig, ax = plt.subplots(figsize=(8.2, 5.0))
    for terrain in ["flat", "slope", "stairs"]:
        chunks = terrain_errors.get(terrain)
        if not chunks:
            continue
        all_err = np.concatenate(chunks)
        all_err = np.sort(all_err)
        cdf = np.linspace(0.0, 1.0, len(all_err), endpoint=False)
        ax.plot(
            all_err,
            cdf,
            label=f"{terrain} (mean={all_err.mean():.3f})",
            color=color_map.get(terrain),
            linewidth=1.8,
        )

    ax.set_title("CDF of Absolute VX Tracking Error")
    ax.set_xlabel("|base_lin_vx - cmd_vx|")
    ax.set_ylabel("Cumulative probability")
    ax.grid(alpha=0.3)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(output_dir / "terrain_vx_error_cdf.png", dpi=180)
    plt.close(fig)


def load_timeseries_curves(timeseries_dir: Path, repeat_id: int):
    curves = {}
    for csv_path in sorted(timeseries_dir.glob(f"*_r{repeat_id}.csv")):
        scenario_id = csv_path.stem.rsplit("_r", 1)[0]
        terrain = scenario_id.split("_", 1)[0]
        df = pd.read_csv(csv_path)
        if not {"time_s", "base_z", "base_lin_vx"}.issubset(df.columns):
            continue
        curves[terrain] = df[["time_s", "base_z", "base_lin_vx"]].sort_values("time_s")
    return curves


def plot_terrain_timeseries(
    curves: dict,
    value_col: str,
    ylabel: str,
    title: str,
    output_file: Path,
):
    if not curves:
        return
    color_map = {"flat": "#4C78A8", "slope": "#F58518", "stairs": "#54A24B"}
    order = ["flat", "slope", "stairs"]

    fig, ax = plt.subplots(figsize=(10, 4.5))
    for terrain in order:
        if terrain not in curves:
            continue
        df = curves[terrain]
        ax.plot(df["time_s"], df[value_col], linewidth=1.6, label=terrain, color=color_map.get(terrain))

    ax.set_title(title)
    ax.set_xlabel("Time (s)")
    ax.set_ylabel(ylabel)
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(output_file, dpi=180)
    plt.close(fig)


def main():
    args = parse_args()
    input_csv = Path(args.input_csv)
    output_dir = Path(args.output_dir)
    timeseries_dir = Path(args.timeseries_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    raw_df = load_raw_compare(input_csv)
    summary = load_and_aggregate(input_csv)
    save_summary_csv(summary, output_dir)
    plot_key_metrics(summary, output_dir)
    plot_control_metric(summary, output_dir)
    plot_normalized_heatmap(summary, output_dir)
    plot_generalization_retention(summary, output_dir)
    plot_repeat_variability(raw_df, output_dir)
    plot_vx_error_cdf(timeseries_dir, output_dir)

    curves = load_timeseries_curves(timeseries_dir, args.repeat_id)
    plot_terrain_timeseries(
        curves=curves,
        value_col="base_z",
        ylabel="Base Height (m)",
        title=f"Body Height vs Time Across Terrains (r{args.repeat_id})",
        output_file=output_dir / "terrain_base_height_timeseries.png",
    )
    plot_terrain_timeseries(
        curves=curves,
        value_col="base_lin_vx",
        ylabel="Linear Velocity X (m/s)",
        title=f"Linear Velocity vs Time Across Terrains (r{args.repeat_id})",
        output_file=output_dir / "terrain_linear_velocity_timeseries.png",
    )

    print(f"Generated figures in: {output_dir.resolve()}")
    print(f"Timeseries repeat_id: {args.repeat_id}")
    print("Files:")
    print("- terrain_core_metrics.png")
    print("- terrain_action_delta_rate.png")
    print("- terrain_score_heatmap.png")
    print("- terrain_key_metrics_summary.csv")
    print("- terrain_generalization_retention.png")
    print("- terrain_repeat_variability.png")
    print("- terrain_vx_error_cdf.png")
    print("- terrain_base_height_timeseries.png")
    print("- terrain_linear_velocity_timeseries.png")


if __name__ == "__main__":
    main()
